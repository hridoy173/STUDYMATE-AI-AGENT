
import ast
import operator


# Allowed mathematical operations
OPERATORS = {
    ast.Add: operator.add,
    ast.Sub: operator.sub,
    ast.Mult: operator.mul,
    ast.Div: operator.truediv,
    ast.Pow: operator.pow,
    ast.Mod: operator.mod,
    ast.USub: operator.neg,
    ast.UAdd: operator.pos,
}


## calculator function to safely evaluate mathematical expressions

def calculator(expression: str) -> dict:
    """
    Safely calculate a mathematical expression.
    """

    try:
        tree = ast.parse(expression, mode="eval")

        def evaluate(node):

            if isinstance(node, ast.Expression):
                return evaluate(node.body)

            if isinstance(node, ast.Constant):
                if type(node.value) in (int, float):
                    return node.value
                raise ValueError("Invalid number")

            if isinstance(node, ast.BinOp):
                op = OPERATORS.get(type(node.op))

                if op is None:
                    raise ValueError("Unsupported operation")

                left = evaluate(node.left)
                right = evaluate(node.right)

                if isinstance(node.op, ast.Pow) and abs(right) > 10:
                    raise ValueError("Exponent too large")

                result = op(left, right)

                if abs(result) > 1e15:
                    raise ValueError("Result too large")

                return result

            if isinstance(node, ast.UnaryOp):
                op = OPERATORS.get(type(node.op))

                if op is None:
                    raise ValueError("Unsupported operation")

                return op(evaluate(node.operand))

            raise ValueError("Invalid mathematical expression")

        result = evaluate(tree)

        return {
            "success": True,
            "expression": expression,
            "result": result
        }

    except (ValueError, TypeError, SyntaxError, ZeroDivisionError) as e:

        return {
            "success": False,
            "error": str(e)
        }



## quiz_generator function to validate and structure MCQ questions generated by the AI

def quiz_generator(topic: str, questions: list) -> dict:
    """
    Validate and structure MCQ questions generated by the AI.
    Supports correct answers as A/B/C/D or full option text.
    """

    if not isinstance(topic, str) or not topic.strip():
        return {
            "success": False,
            "error": "Topic is required."
        }

    if not isinstance(questions, list) or not questions:
        return {
            "success": False,
            "error": "No questions generated."
        }

    validated_questions = []

    for index, question in enumerate(questions, start=1):

        if not isinstance(question, dict):
            return {
                "success": False,
                "error": f"Question {index} must be an object."
            }

        required_fields = [
            "question",
            "options",
            "correct_answer",
            "explanation"
        ]

        if not all(field in question for field in required_fields):
            return {
                "success": False,
                "error": f"Question {index} has missing fields."
            }

        # Validate question text
        question_text = question["question"]

        if not isinstance(question_text, str) or not question_text.strip():
            return {
                "success": False,
                "error": f"Question {index} has invalid question text."
            }

        # Validate options
        options = question["options"]

        if not isinstance(options, list) or len(options) != 4:
            return {
                "success": False,
                "error": f"Question {index} must have exactly 4 options."
            }

        if not all(
            isinstance(option, str) and option.strip()
            for option in options
        ):
            return {
                "success": False,
                "error": f"Question {index} has invalid options."
            }

        # Normalize options
        options = [option.strip() for option in options]

        # Get correct answer
        correct_answer = str(
            question["correct_answer"]
        ).strip()

        # Convert A/B/C/D into option text
        letters = ["A", "B", "C", "D"]

        if correct_answer.upper() in letters:
            answer_index = letters.index(correct_answer.upper())
            correct_answer = options[answer_index]

        # Match answer text with options
        matched_answer = next(
            (
                option for option in options
                if option.casefold() == correct_answer.casefold()
            ),
            None
        )

        if matched_answer is None:
            return {
                "success": False,
                "error": (
                    f"Question {index} has an invalid correct answer. "
                    f"Received: {correct_answer!r}. "
                    f"Available options: {options}"
                )
            }

        # Validate explanation
        explanation = question["explanation"]

        if not isinstance(explanation, str) or not explanation.strip():
            return {
                "success": False,
                "error": f"Question {index} has invalid explanation."
            }

        validated_questions.append({
            "question": question_text.strip(),
            "options": options,
            "correct_answer": matched_answer,
            "explanation": explanation.strip()
        })

    return {
        "success": True,
        "topic": topic.strip(),
        "total_questions": len(validated_questions),
        "questions": validated_questions
    }



## notes_summarizer function to validate and prepare study notes for summarization

def notes_summarizer(text: str) -> dict:
    """
    Validate and prepare study notes for summarization.
    """

    if not isinstance(text, str) or not text.strip():
        return {
            "success": False,
            "error": "Notes cannot be empty."
        }

    if len(text) < 30:
        return {
            "success": False,
            "error": "Please provide at least 30 characters of notes."
        }

    return {
        "success": True,
        "original_length": len(text),
        "notes": text.strip()
    }



## study_planner function to generate a structured study plan for students

def study_planner(subject: str,topics: list,days: int,hours_per_day: float) -> dict:
    """
    Generate a structured study plan for students.
    """

    if not isinstance(subject, str) or not subject.strip():
        return {
            "success": False,
            "error": "Subject is required."
        }

    if not isinstance(topics, list) or not topics:
        return {
            "success": False,
            "error": "At least one topic is required."
        }

    if not isinstance(days, int) or days < 1 or days > 30:
        return {
            "success": False,
            "error": "Days must be between 1 and 30."
        }

    if (
        not isinstance(hours_per_day, (int, float))
        or isinstance(hours_per_day, bool)
        or not 0 < hours_per_day <= 12
    ):
        return {
            "success": False,
            "error": "Hours per day must be between 0 and 12."
        }

    topics = [
        topic.strip()
        for topic in topics
        if isinstance(topic, str) and topic.strip()
    ]

    if not topics:
        return {
            "success": False,
            "error": "No valid topics provided."
        }

    total_topics = len(topics)
    study_plan = []

    # Distribute topics across available days
    for day in range(days):

        start = day * total_topics // days
        end = (day + 1) * total_topics // days

        daily_topics = topics[start:end]

        tasks = []

        if daily_topics:
            topic_hours = hours_per_day / len(daily_topics)

            for topic in daily_topics:
                tasks.append({
                    "topic": topic,
                    "duration_hours": round(topic_hours, 2)
                })
        else:
            tasks.append({
                "topic": "Revision and practice",
                "duration_hours": hours_per_day
            })

        study_plan.append({
            "day": day + 1,
            "tasks": tasks,
            "total_hours": hours_per_day
        })

    return {
        "success": True,
        "subject": subject.strip(),
        "total_days": days,
        "hours_per_day": hours_per_day,
        "total_topics": total_topics,
        "study_plan": study_plan
    }

